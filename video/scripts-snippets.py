#!/usr/bin/env python3
"""Write video/src/sponsors/snippets.ts: verbatim excerpts (path, first line, text) of repo files for code cards."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EX = {
    "envioConfig": ("indexer/config.yaml", 8, 37),
    "envioSchema": ("indexer/schema.graphql", 30, 41),
    "envioHandler": ("indexer/src/handlers/CargoNoteMarket.ts", 20, 26),
    "failover": ("backend/internal/chain/failover.go", 24, 30),
    "failoverRT": ("backend/internal/chain/failover.go", 146, 157),
    "alchemyCfg": ("backend/internal/config/config.go", 243, 252),
    "maxRange": ("backend/internal/config/config.go", 276, 279),
}
out = ["// Generated by scripts-snippets.py: verbatim excerpts of repository files for the sponsor videos' code cards.", ""]
for k, (p, a, b) in EX.items():
    lines = open(os.path.join(ROOT, p)).read().split("\n")[a - 1:b]
    out.append(f"export const {k} = {json.dumps({'path': p, 'first': a, 'code': chr(10).join(lines)})};")
open(os.path.join(ROOT, "video", "src", "sponsors", "snippets.ts"), "w").write("\n".join(out) + "\n")
print("ok")
